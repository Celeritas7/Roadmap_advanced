// Phase 1 smoke: Keep/Delete go through an Undo strip; Undo restores; the
// write lands only after the strip expires; New folder is inline.
import { chromium } from 'playwright'
const base = process.env.HARNESS_URL || 'http://localhost:5173'
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined })
const p = await b.newPage({ viewport: { width: 1100, height: 900 } })
const fails = []
const check = (name, ok) => { console.log((ok ? 'ok   ' : 'FAIL ') + name); if (!ok) fails.push(name) }
const tree = () => p.evaluate(() => window.rmStore.getState().tree)
const has = async (id) => (await tree()).some((t) => t.id === id)
const parked = async (id) => (await tree()).find((t) => t.id === id)?.tags.includes('parked')

await p.goto(base + '/scripts/harness/inbox.html')
await p.waitForSelector('.ib-item')
check('10 cards render', (await p.locator('.ib-item').count()) === 10)
check('a blank link label shows the host', (await p.locator('.ib-links .ns-link').allTextContents()).join('|') === 'N3 goi|youtu.be')
check('no native dialogs: Delete shows a strip', await (async () => {
  p.once('dialog', (d) => { fails.push('native dialog opened: ' + d.message()); d.dismiss() })
  await p.locator('.ib-item', { hasText: 'Goi practice' }).getByRole('button', { name: 'Delete' }).click()
  return (await p.locator('.ib-strip.delete').count()) === 1
})())
check('live region announces', (await p.locator('.sr-only').textContent()).startsWith('Deleted: Goi'))
check('row still in store while strip shows', await has('t2'))
await p.locator('.ib-strip', { hasText: 'Goi practice' }).getByRole('button', { name: 'Undo' }).click()
check('Undo restores the card', (await p.locator('.ib-item', { hasText: 'Goi practice' }).count()) === 1 && await has('t2'))

await p.locator('.ib-item', { hasText: 'Sheet metal' }).getByRole('button', { name: 'Delete' }).click()
await p.locator('.ib-item', { hasText: 'Python code' }).getByRole('button', { name: 'Keep' }).click()
check('two strips', (await p.locator('.ib-strip').count()) === 2)
await p.waitForTimeout(5400)
check('after 5 s: delete written', !(await has('t4')))
check('after 5 s: keep written (unparked)', (await has('t3')) && !(await parked('t3')))
check('strips gone', (await p.locator('.ib-strip').count()) === 0)

// Inline new folder from a card's Move to…
const card = p.locator('.ib-item', { hasText: 'Mark Japanese' })
await card.getByLabel('Move to folder').selectOption('__new__')
check('inline field opens, no prompt()', (await card.locator('.ib-input').count()) === 1)
await card.locator('.ib-input').fill('Kanji drills')
await card.getByRole('button', { name: 'Create & move' }).click()
const t1 = (await tree()).find((t) => t.id === 't1')
const nf = (await tree()).find((t) => t.title === 'Kanji drills' && t.kind === 'group')
check('folder created at top level and task moved into it', !!nf && nf.parent_id === null && t1.parent_id === nf.id)

// Mechanical's two items were kept/deleted above, so its chip is gone.
check('emptied folder chip disappears', (await p.getByRole('button', { name: /^Mechanical/ }).count()) === 0)
// Folder bar: Keep all → strips for every card in the folder
check('same-named folders get distinct chips', (await p.getByRole('button', { name: /^From OneNote › Japanese/ }).count()) === 1 && (await p.getByRole('button', { name: /^Languages › Japanese/ }).count()) === 1)
await p.getByRole('button', { name: /^From OneNote › Japanese/ }).click()
check('folder chip filters', (await p.locator('.ib-item').count()) === 1)
await p.getByRole('button', { name: /Keep all/ }).click()
check('Keep all strips every shown card', (await p.locator('.ib-strip.keep').count()) === 1)

// Phase 2: pills + picker, link host labels, phone layout
await p.locator('.ib-folders').getByRole('button', { name: /^All \d/ }).click()
const mj = p.locator('.ib-item', { hasText: 'Mark Japanese' })
check('pills show current values', (await mj.locator('.ib-pill').allTextContents()).join('|') === 'home|quick|either|any energy|normal|from folder')
await mj.getByRole('button', { name: /^Where:/ }).click()
check('picker opens with 44px rows', await mj.locator('.ib-opt').first().evaluate((el) => el.getBoundingClientRect().height >= 44))
await p.keyboard.press('Escape')
check('Esc closes the picker', (await p.locator('.ib-pop').count()) === 0)
await mj.getByRole('button', { name: /^Effort:/ }).click()
await p.getByRole('option', { name: 'deep' }).click()
const t1b = (await tree()).find((t) => t.id === 't1')
check('pick writes the tag and swaps the old one', t1b.tags.includes('deep-focus') && !t1b.tags.includes('short-burst'))
check('pill reflects the new value', (await mj.getByRole('button', { name: /^Effort:/ }).textContent()) === 'deep')
// Phase 3: multi-select, range, bulk rule/move/keep/delete with one Undo
await p.getByRole('button', { name: /^Home, food/ }).click()
const home = (name) => p.locator('.ib-item', { hasText: name })
await home('Wash clothes').getByRole('checkbox').click()
await home('Clean the fridge').getByRole('checkbox').click({ modifiers: ['Shift'] })
check('shift-click selects the range (4)', (await p.locator('.ib-item.sel').count()) === 4)
check('bulk bar shows the count', (await p.locator('.ib-bar-n').textContent()) === '4 selected')
await p.locator('.ib-bar').getByLabel('Set a rule on selected').selectOption('place:home')
const homeTagged = (await tree()).filter((t) => ['h0', 'h1', 'h2', 'h3'].includes(t.id) && t.tags.includes('home')).length
check('Set rule tags all 4 in one batch call', homeTagged === 4 && (await p.evaluate(() => window.batchCalls)) === 1)
check('selection survives Set rule', (await p.locator('.ib-item.sel').count()) === 4)
await p.locator('.ib-bar').getByRole('button', { name: 'Delete' }).click()
check('one batch strip replaces 4 cards', (await p.locator('.ib-strip.delete').count()) === 1 && (await p.locator('.ib-strip-t').first().textContent()) === '4 items')
check('nothing deleted yet', await (async () => { const ids = new Set((await tree()).map((t) => t.id)); return ['h0', 'h1', 'h2', 'h3', 'h4'].every((id) => ids.has(id)) })())
check('selection cleared, bar gone', (await p.locator('.ib-bar').count()) === 0)
await p.locator('.ib-strip.delete').getByRole('button', { name: 'Undo' }).click()
check('Undo brings all 4 back', (await p.locator('.ib-item').count()) === 5)
await p.getByRole('checkbox', { name: /^Select all/ }).click()
check('Select all selects 5', (await p.locator('.ib-item.sel').count()) === 5)
await p.locator('.ib-bar').getByLabel('Move selected to folder').selectOption({ label: 'Languages › Japanese' })
const moved = (await tree()).filter((t) => t.id.startsWith('h') && t.parent_id === 'lang-ja').length
check('Move to moves all 5 in one batch', moved === 5 && (await p.evaluate(() => window.batchCalls)) === 2)
await p.getByRole('button', { name: /^Languages › Japanese/ }).click()
await p.locator('.ib-folders').getByRole('button', { name: /^All \d/ }).click()
await home('Cook rice').getByRole('checkbox').click()
await home('Make curry').getByRole('checkbox').click()
await p.locator('.ib-bar').getByRole('button', { name: 'Keep' }).click()
await p.waitForTimeout(5400)
const kept = (await tree()).filter((t) => ['h1', 'h2'].includes(t.id) && !t.tags.includes('parked')).length
check('batch Keep unparks both after 5 s in one call', kept === 2 && (await p.evaluate(() => window.batchCalls)) === 3)

await p.setViewportSize({ width: 390, height: 800 })
const tgt = await mj.locator('.ib-pill').first().evaluate((el) => el.getBoundingClientRect().height)
check('phone: pills are 44px tall', tgt >= 44)
await p.screenshot({ path: process.env.SHOT_PHONE || 'scripts/harness/phone.png', fullPage: true })
await p.setViewportSize({ width: 1100, height: 900 })

// Phase 4: review mode, keys, counter, sort
await p.locator('.ib-folders').getByRole('button', { name: /^All \d/ }).click()
const before = await p.locator('.ib-count').textContent()
await p.getByRole('button', { name: 'Review one by one' }).click()
check('review shows one card', (await p.locator('.ib-review').count()) === 1 && (await p.locator('.ib-item').count()) === 0)
const title = async () => (await p.locator('.ib-rv-title').textContent()).trim()
const r0 = await title()
await p.keyboard.press('s')
const r1 = await title()
check('s skips to the next item', r1 !== r0)
await p.keyboard.press('ArrowLeft')
check('← goes back', (await title()) === r0)
await p.keyboard.press('3')
const cur = (await tree()).find((t) => t.title === r0)
check('3 sets effort deep on the current item', cur.tags.includes('deep-focus'))
await p.keyboard.press('d')
check('d deletes: strip shows, next card loads', (await p.locator('.ib-strip.delete').count()) === 1 && (await title()) !== r0)
const n1 = Number((await p.locator('.ib-count').textContent()).split(' ')[0])
check('counter goes up on a decision', n1 === Number(before.split(' ')[0]) + 1)
await p.keyboard.press('u')
check('u undoes the last decision', (await p.locator('.ib-strip.delete').count()) === 0 && (await tree()).some((t) => t.title === r0))
check('counter goes back down on undo', Number((await p.locator('.ib-count').textContent()).split(' ')[0]) === n1 - 1)
const r2 = await title()
await p.keyboard.press('k')
check('k keeps', (await p.locator('.ib-strip.keep').count()) === 1 && (await title()) !== r2)
check('review context line renders', (await p.locator('.ib-rv-meta').textContent()).includes('Right now:'))
await p.keyboard.press('Escape')
check('Esc returns to the list', (await p.locator('.ib-review').count()) === 0 && (await p.locator('.ib-item').count()) > 0)
await p.getByLabel('Sort').selectOption('links')
await p.waitForTimeout(5400)   // let the review Keep commit so its card is gone
await p.evaluate(() => window.rmStore.setState({ resources: [...window.rmStore.getState().resources, { id: 'r3', task_id: 'h4', label: 'link', url: 'https://maps.app.goo.gl/x', kind: 'web', position: 0, created_at: '' }] }))
check('sort "with links first" puts a linked item on top', (await p.locator('.ib-item').first().locator('.ib-links').count()) === 1)
check('sort "with links first" orders linked before unlinked', await p.locator('.ib-item').evaluateAll((els) => { const f = els.map((e) => !!e.querySelector('.ib-links')); return f.indexOf(false) === -1 || f.lastIndexOf(true) < f.indexOf(false) }))
await p.getByLabel('Sort').selectOption('folder')

// Phase 4b: stale badge; Keep clears stale and marks kept. Earlier review
// steps may have acted on t5, so put it back in its stale state first.
await p.evaluate(() => {
  const s = window.rmStore.getState()
  const base = s.tree.find((t) => t.id === 't5') ?? { ...s.tree.find((t) => t.id === 't1'), id: 't5', title: 'Back from last month', parent_id: 'lang-ja' }
  window.rmStore.setState({ tree: [...s.tree.filter((t) => t.id !== 't5'), { ...base, tags: ['kept', 'parked', 'stale'] }] })
})
const st = p.locator('.ib-item', { hasText: 'Back from last month' })
check('stale item shows its badge', (await st.locator('.ib-stale').count()) === 1)
await st.getByRole('button', { name: 'Keep' }).click()
await p.waitForTimeout(5400)
const t5 = (await tree()).find((t) => t.id === 't5')
check('Keep clears parked + stale, keeps one kept tag', !t5.tags.includes('parked') && !t5.tags.includes('stale') && t5.tags.filter((x) => x === 'kept').length === 1)
const t3k = (await tree()).find((t) => t.id === 't3')
check('a plain Keep marks the task kept', t3k.tags.includes('kept'))

// Phase 5: quick capture
